// The names StarCraft 1.16.1's own image, sound and portrait tables give, as the prober derives them, written to
// `src/stockNames.ts`. A maintainer's tool, run by hand where an unmodified 1.16.1 is installed (CI has none):
//
//   node scripts/stock-names.mjs <the game's folder>            writes src/stockNames.ts
//   node scripts/stock-names.mjs <the game's folder> --check    exits 1 when the file is not what it would write
//
// It reads `arr\images.tbl`, `arr\sfxdata.tbl` and `arr\portdata.tbl` from the game's archives as the game lays them
// (`patch_rt.mpq` over `BrooDat.mpq` over `StarDat.mpq`), checks that `StarCraft.exe` beside them is 1.16.1, and keeps
// the names only: no byte of the game goes into the repository. It needs Node 22.18 or later (it imports the sources).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";
import { Archive } from "mopaq";
import { NAMING_TABLES, tblStrings } from "../src/names.ts";
import { gameName } from "../src/gameNames.ts";

const [folder, mode] = process.argv.slice(2);
if (!folder) { console.error("usage: node scripts/stock-names.mjs <the game's folder> [--check]"); process.exit(2); }
const OUT = new URL("../src/stockNames.ts", import.meta.url).pathname;
const ARCHIVES = ["patch_rt.mpq", "BrooDat.mpq", "StarDat.mpq"];

/** The game's version, from `StarCraft.exe`'s version resource (VS_FIXEDFILEINFO's file version). */
function exeVersion(bytes) {
  const at = bytes.indexOf(Buffer.from([0xbd, 0x04, 0xef, 0xfe]));
  if (at < 0) return null;
  const ms = bytes.readUInt32LE(at + 8), ls = bytes.readUInt32LE(at + 12);
  return [ms >>> 16, ms & 0xffff, ls >>> 16, ls & 0xffff].join(".");
}
const version = exeVersion(readFileSync(join(folder, "StarCraft.exe")));
if (version !== "1.16.1.1") { console.error(`StarCraft.exe in ${folder} is ${version ?? "of no version"}, not 1.16.1.1`); process.exit(1); }

const archives = ARCHIVES.map((name) => ({ name, archive: Archive.open(new Uint8Array(readFileSync(join(folder, name)))) }));
const names = new Set(), from = [];
for (const [table, under] of NAMING_TABLES) {
  const holder = archives.find((a) => a.archive.fileInfo(table));
  if (!holder) { console.error(`${table} is in none of ${ARCHIVES.join(", ")}`); process.exit(1); }
  const bytes = holder.archive.readFile(table);
  const strings = tblStrings(bytes);
  // (as the prober takes a table's strings: each non-empty one under its folder, as the game names it)
  for (const n of strings) if (n) names.add(gameName(under + n));
  from.push(`${table} from ${holder.name}: ${bytes.length} bytes, SHA-256 ${createHash("sha256").update(bytes).digest("hex")}, ${strings.length} strings`);
}

// Grouped by folder: the folders sorted, each once with its names after it, sorted.
const sorted = [...names].sort();
const groups = new Map();
for (const n of sorted) {
  const cut = n.lastIndexOf("\\") + 1, dir = n.slice(0, cut);
  if (!groups.has(dir)) groups.set(dir, []);
  groups.get(dir).push(n.slice(cut));
}
// One line a folder: the folder (with its trailing backslash), then its names, separated by spaces, wrapped at 118
// columns with the rest of a folder's names indented. No name holds a space, a backtick or `${`.
for (const n of sorted) if (/[\s`$]/.test(n)) { console.error(`a name the list cannot hold as text: ${JSON.stringify(n)}`); process.exit(1); }
const lineOf = (dir, leaves) => {
  const lines = [];
  let line = dir;
  for (const leaf of leaves) {
    if (line.length + 1 + leaf.length > 118) { lines.push(line); line = `  ${leaf}`; } else line += ` ${leaf}`;
  }
  lines.push(line);
  return lines.join("\n");
};
const body = [...groups].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([dir, leaves]) => lineOf(dir, leaves)).join("\n");
const text = `// Generated by scripts/stock-names.mjs: do not edit. The names StarCraft 1.16.1's own tables give: every string of its
// image, sound and portrait tables under the folder each names files in, as the game names them (\`gameName\`), the way
// the prober takes them from an archive's own tables. Names only, from the unmodified game (StarCraft.exe ${version}):
${from.map((f) => `//   ${f}`).join("\n")}
// ${sorted.length} names in ${groups.size} folders.

/**
 * One line a folder, the folders sorted: the folder (its trailing backslash kept), then the names in it, sorted, each
 * after a space; a folder's names go on over the lines indented below it. A name is the folder and the name joined.
 */
export const STOCK_TABLE_NAMES = String.raw\`
${body}
\`;
`;
if (mode === "--check") {
  let now = "";
  try { now = readFileSync(OUT, "utf8"); } catch { /* none */ }
  if (now !== text) { console.error(`${OUT} is not what the game's tables give: run the script without --check`); process.exit(1); }
  console.log(`${OUT}: as the game's tables give it (${sorted.length} names)`);
} else {
  writeFileSync(OUT, text);
  console.log(`${OUT}: ${sorted.length} names in ${groups.size} folders, ${Buffer.byteLength(text)} bytes`);
}
